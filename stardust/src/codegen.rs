use crate::class::merged_local_fields;
use crate::ir::{Ir, Type};
use std::collections::BTreeSet;

impl Ir {
    /// Thin Rust wrappers for `Handle::link` / export field get-set / export methods.
    /// Generated text is not the crate API; `.sd` remains `>>`.
    pub fn to_rust_handles(&self) -> String {
        let mut out =
            String::from("// Generated by Ir::to_rust_handles. Call the host Handle API.\n");
        for (class_name, class) in &self.classes {
            out.push_str(&format!("pub struct {class_name};\n"));
            let mut body = String::new();
            let mut has_link = false;
            if let Ok(Type::Struct(st)) = self.layout(&class.layout) {
                for f in &st.fields {
                    if matches!(f.ty, Type::Link) {
                        has_link = true;
                        body.push_str(&format!(
                            "    pub fn link_{}(h: &mut stardust::Handle, db: &stardust::Handle, region: &mut stardust::Region) -> stardust::Result<()> {{\n        h.link(\"{}\", db, region)\n    }}\n",
                            f.name, f.name
                        ));
                    }
                }
            }
            let mut used = BTreeSet::new();
            if has_link {
                for f in class_link_fields(self, class_name) {
                    used.insert(format!("link_{f}"));
                }
                for (db_name, db) in &self.classes {
                    if db.export_fields.is_empty() && db.export_methods.is_empty() {
                        continue;
                    }
                    let prefix = rust_mod_ident(db_name);
                    for (field_name, field) in &db.export_fields {
                        let size = self
                            .layout(&field.layout)
                            .map(|t| t.inline_size())
                            .unwrap_or(0);
                        let get_name = unique_fn(&mut used, field_name, &prefix);
                        let set_name = unique_fn(&mut used, &format!("set_{field_name}"), &prefix);
                        body.push_str(&format!(
                            "    pub fn {get_name}(h: &stardust::Handle, region: &mut stardust::Region, value_off: u64) -> stardust::Result<()> {{\n        h.field_retrieve(\"{field_name}\", region, value_off, {size})\n    }}\n"
                        ));
                        body.push_str(&format!(
                            "    pub fn {set_name}(h: &stardust::Handle, region: &mut stardust::Region, value_off: u64) -> stardust::Result<()> {{\n        h.field_assign(\"{field_name}\", region, value_off, {size})\n    }}\n"
                        ));
                    }
                    for method_name in db.export_methods.keys() {
                        let fn_name = unique_fn(&mut used, method_name, &prefix);
                        body.push_str(&format!(
                            "    pub fn {fn_name}(h: &stardust::Handle, region: &mut stardust::Region) -> stardust::Result<stardust::CallRet> {{\n        h.call_export(\"{method_name}\", region)\n    }}\n"
                        ));
                    }
                }
            }
            let prefix = rust_mod_ident(class_name);
            if let Ok(locals) = merged_local_fields(self, class_name) {
                for (field_name, field) in locals {
                    let size = self
                        .layout(&field.layout)
                        .map(|t| t.inline_size())
                        .unwrap_or(0);
                    let get_name = unique_fn(&mut used, &field_name, &prefix);
                    let set_name = unique_fn(&mut used, &format!("set_{field_name}"), &prefix);
                    body.push_str(&format!(
                        "    pub fn {get_name}(h: &stardust::Handle, region: &mut stardust::Region, value_off: u64) -> stardust::Result<()> {{\n        h.field_retrieve(\"{field_name}\", region, value_off, {size})\n    }}\n"
                    ));
                    body.push_str(&format!(
                        "    pub fn {set_name}(h: &stardust::Handle, region: &mut stardust::Region, value_off: u64) -> stardust::Result<()> {{\n        h.field_assign(\"{field_name}\", region, value_off, {size})\n    }}\n"
                    ));
                }
            }
            if !body.is_empty() {
                out.push_str(&format!("impl {class_name} {{\n{body}}}\n"));
            }
        }
        out
    }
}

fn class_link_fields(ir: &Ir, class_name: &str) -> Vec<String> {
    let Ok(class) = ir.class(class_name) else {
        return Vec::new();
    };
    let Ok(Type::Struct(st)) = ir.layout(&class.layout) else {
        return Vec::new();
    };
    st.fields
        .iter()
        .filter(|f| matches!(f.ty, Type::Link))
        .map(|f| f.name.clone())
        .collect()
}

fn unique_fn(used: &mut BTreeSet<String>, name: &str, prefix: &str) -> String {
    if used.insert(name.to_string()) {
        name.to_string()
    } else {
        let prefixed = format!("{prefix}_{name}");
        used.insert(prefixed.clone());
        prefixed
    }
}

fn rust_mod_ident(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    if out.is_empty() {
        "ident".into()
    } else {
        out
    }
}
